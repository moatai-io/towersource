/** Populate a new guide only. Existing organization edits survive startup and upgrades. */
export function seedIntroductionGuides(rootPath: string): void {
  const docsPath = path.join(rootPath, 'docs');
  fs.mkdirSync(docsPath, { recursive: true });
  for (const [name, body] of Object.entries(INTRODUCTION_GUIDES)) {
    const file = path.join(docsPath, name);
    try { fs.writeFileSync(file, body, { encoding: 'utf8', flag: 'wx' }); }
    catch (error: any) { if (error?.code !== 'EEXIST') throw error; }
  }
}
