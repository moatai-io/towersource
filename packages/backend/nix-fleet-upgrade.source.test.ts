import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';

const read = (relative: string) => fs.readFileSync(path.join(process.cwd(), relative), 'utf8');
const fleet = read('scripts/fleet/upgrade-fleet-production');
const remote = read('scripts/fleet/fleet-nix-remote');
const start = read('start.sh');
const fast = read('scripts/fleet/fleet-deploy-fast');
const durableRun = read('scripts/fleet/fleet-deploy-run');
const fleetPatch = read('scripts/fleet/fleet-patch');
const prefetch = read('scripts/fleet/fleet-nix-prefetch.sh');
const signedClosure = read('scripts/nix-supply-chain/prefetch-signed-closure');

describe('signed Nix fleet upgrade orchestrator source contract', () => {
  it('requires an explicit ordered target list and full revision approval', () => {
    expect(fleet).toContain('plan --targets CUSTOMER[,CUSTOMER...]');
    expect(fleet).toContain('apply --targets CUSTOMER[,CUSTOMER...] --approve-rev FULL_REV');
    expect(fleet).toContain('duplicate target');
    expect(fleet).toContain('target is retired or non-deployable');
    expect(fleet).toContain('at least one explicit target is required');
    expect(fleet).not.toContain('--all');
  });

  it('uses an explicitly requested promoted ancestor even when Operator production advanced', () => {
    expect(fleet).toContain('rev="${requested_rev:-$operator_rev}"');
    expect(fleet).toContain('merge-base --is-ancestor "$rev" "$origin_rev"');
    expect(fleet).toContain('requested promoted revision must remain in origin/main history before fleet rollout');
    expect(fleet).toContain("'operatorCurrentRev':operator_rev");
    expect(fleet).toContain("'operatorAheadOfTarget':operator_rev!=rev");
    expect(fleet).not.toContain('requested revision is not current Operator production');
    expect(fleet).toContain('revision is not in promotion ledger');
    expect(fleet).toContain('revision is not fully Fleet-promoted');
    expect(fleet).toContain('promotion evidence is incomplete');
    expect(fleet).toContain("'tower-app-probe','prod-upgrade-prepare'");
    expect(fleet).toContain('packages/backend/db/migrations');
    expect(fleet).toContain('target_sql_migrations=');
    expect(fleet).toContain('ls-tree -r --name-only "$rev" -- packages/backend/db/migrations');
    expect(fleet).toContain('all_sql=[x for x in target_sql_migrations.splitlines() if x]');
    expect(fleet).toContain("keys=[x.rsplit('/',1)[-1].removesuffix('.sql') for x in all_sql");
    expect(fleet).toContain("deferredDbMigrationChanges':sorted(deferred)");
    expect(fleet).toContain("TOWER_ROLE:'managed'");
    expect(fleet).not.toContain("TOWER_ROLE:'managed',TOWER_TURN_REWIND_ENABLED:'false'");
    expect(fleet).toContain("mod.shouldDeferMigrationForVm(file.split('/').pop(),env)");
    expect(fleet).toContain('--approve-db-migrations FULL_REV');
    expect(fleet).toContain('pending DB migrations require --approve-db-migrations with the exact approved revision');
    expect(fleet).toContain("dbMigrationPolicy':'backup-then-transactional-apply-before-cutover'");
    expect(fleet).toContain("[cmd,'migration-status',target]");
  });

  it('keeps organization skill sync out of the required cutover verification path', () => {
    expect(fleet).not.toContain('TOWER_FLEET_SKILLS_CMD');
    expect(fleet).not.toContain('$fleet_skills_cmd sync "$customer" --apply --materialize --json');
    expect(fleet).not.toContain('organization skill sync or project materialization failed');
    expect(fleetPatch).toContain('fleet-patch follow-up CUSTOMER');
    expect(fleetPatch).toContain('followup_cmd');
  });

  it('isolates customer failures and keeps canary opt-in', () => {
    expect(fleet).toContain('prestage_customer()');
    expect(fleet).toContain('cutover_verify_customer()');
    expect(fleet).toContain('write_state prestage-running');
    expect(fleet).toContain('without service or database mutation');
    expect(fleet).toContain('--canary');
    expect(fleet).toContain('canary_enabled="false"');
    expect(fleet).toContain('optional canary runs first; its result does not block other approved customers');
    expect(fleet).toContain('prestaged_customers+=("$customer")');
    expect(fleet).toContain('cutting over every successfully prestaged customer independently');
    expect(fleet).toContain('rollout completed all eligible customers with isolated failures');
    expect(fleet).toContain('customer worker exited without a result file');
    expect(fleet).toContain('customer worker aborted before writing a detailed result');
    expect(fleet).toContain('[[ -f "$result_file" ]] || customer_fail');
    expect(fleet).toContain('append_result "${files[$i]}" "${batch[$i]}"');
    expect(fleet).toContain('durable_customer_dir="$durable_run_dir/customers"');
    expect(fleet).toContain('customer_log_file()');
    expect(fleet).toContain('>"$(customer_log_file "$customer" prestage)" 2>&1');
    expect(fleet).toContain('>"$(customer_log_file "$customer" cutover-verify)" 2>&1');
    expect(fleet).not.toContain('>"$work_dir/$customer.log" 2>&1');
    expect(fleet).not.toContain('follower cutover not started');
    expect(fleet).not.toContain('one or more customers failed during non-mutating prestage; no cutover started');
    expect(fleet).toContain('TOWER_FLEET_UPGRADE_PRESTAGE_PARALLELISM:-5');
    expect(fleet).toContain('TOWER_FLEET_UPGRADE_CUTOVER_PARALLELISM:-5');
    expect(fleet).toContain('prestage parallelism above 5 requires a reviewed code change');
    expect(fleet).toContain('cutover parallelism above 5 requires a reviewed code change');
    expect(fleet).toContain('offset+=prestage_parallelism');
    expect(fleet).toContain('offset+=cutover_parallelism');
    expect(fleet).toContain('write_state parallel-running');
    expect(fleet).toContain('cutover_verify_customer "$customer"');
    expect(fleet).toContain('for ((offset=0; offset<${#followers[@]}; offset+=cutover_parallelism))');
    expect(fleet).not.toContain('((failed == 0)) || break');
    expect(fleet).toContain('customer_fail "$stage_file" "$customer" snapshot');
    expect(fleet).toContain('customer_fail "$stage_file" "$customer" align');
    expect(fleet).toContain('customer_fail "$stage_file" "$customer" prefetch');
    expect(fleet).toContain('customer_fail "$result_file" "$customer" backup');
    expect(fleet).toContain('customer_fail "$result_file" "$customer" migration');
    expect(fleet).toContain('TOWER_FLEET_PUBLIC_KEY_FILE');
    expect(fleet).toContain('TOWER_FLEET_PUBLIC_KEY_READ_CMD');
    expect(fleet).toContain('TOWER_FLEET_SSH_OWNER');
    expect(fleet).toContain('$public_key_read_cmd "$public_key_file" >"$public_key_tmp"');
    expect(fleet).toContain('read_root_file "$ledger" >"$promotion_ledger_tmp"');
    expect(fleet).toContain('chown "$ssh_owner" "$public_key_tmp" "$promotion_ledger_tmp"');
    expect(fleet).toContain('run_as_ssh_owner "$prefetch_cmd"');
    expect(fleet).toContain('sudo -n -u "$ssh_owner" "$@"');
    expect(fleet).toContain('--public-key-file "$public_key_tmp"');
    expect(fleet).toContain('--ledger "$promotion_ledger_tmp"');
    expect(fleet).toContain('customer_fail "$result_file" "$customer" cutover');
    expect(fleet).toContain('customer_fail "$result_file" "$customer" verify');
    expect(fleet).toContain('timings="${5-}"');
    expect(fleet).toContain("[[ -n \"$timings\" ]] || timings='{}'");
    expect(fleet).toContain('invalid timings JSON');
    expect(fleet).not.toContain('timings="${5:-{}}"');
    expect(fleet).toContain('data row-count regression');
    expect(fleet).toContain('authenticated data smoke failed');
    expect(fleet.indexOf('run_as_ssh_owner "$prefetch_cmd"')).toBeLessThan(fleet.indexOf('$remote_cmd backup-db "$customer"'));
    expect(fleet.indexOf('$remote_cmd backup-db "$customer"')).toBeLessThan(fleet.indexOf('$remote_cmd migrate-db "$customer"'));
    expect(fleet.indexOf('$remote_cmd migrate-db "$customer"')).toBeLessThan(fleet.indexOf('"$remote_cmd" cutover "$customer"'));
    expect(fleet.indexOf('"$remote_cmd" cutover "$customer"')).toBeLessThan(fleet.indexOf('verification="$($remote_cmd promote-verify'));
    expect(fleet).toContain("x['prestageTotal']");
    expect(fleet).toContain("x['cutoverVerifyTotal']");
    expect(fleet).toContain("'timingsMs':timings");
  });

  it('runs mutating rollout in a detached owner and persists structured state', () => {
    expect(fleet).toContain('runner_args=(__detached_runner');
    expect(fleet).toContain('setsid nohup "$0" "${runner_args[@]}"');
    expect(fleet).toContain("write_state detached");
    expect(fleet).toContain('all successfully prestaged customers completed independent signed Nix rollout');
    expect(fleet).toContain("write_state failed");
    expect(fleet).toContain("'currentCustomer'");
    expect(fleet).toContain("'customerStates'");
    expect(fleet).toContain("'summary'");
    expect(fleet).toContain("['queued','transferring','prestaged','cutting-over','verified','failed']");
    expect(fleet).toContain('update_customer_state "$customer" transferring prestage');
    expect(fleet).toContain('update_customer_state "$customer" prestaged prestage');
    expect(fleet).toContain('update_customer_state "$customer" cutting-over cutover');
    expect(fleet).toContain('update_customer_state "$customer" verified verify');
  });

  it('keeps candidate, cutover and post-cutover promotion as separate remote phases', () => {
    expect(remote).toContain('migration-status <customer>');
    expect(remote).toContain('$HOME/apps/tower/.git');
    expect(remote).toContain('remote_repo_path="$(remote_repo)"');
    expect(remote).not.toContain('cd ~/tower');
    expect(remote).toContain('data-snapshot <customer>');
    expect(remote).toContain("'projectMembers'");
    expect(remote).toContain('authenticated-smoke <customer>');
    expect(remote).toContain("COALESCE(u.disabled,0)=0");
    expect(remote).toContain("CASE WHEN u.role NOT IN ('admin','operator') THEN 0 ELSE 1 END");
    expect(remote).toContain('active representative user or JWT_SECRET missing');
    expect(remote).toContain('/api/projects');
    expect(remote).toContain('/api/sessions');
    expect(remote).toContain('backup-db <customer> --source-rev FULL_REV');
    expect(remote).toContain('pg_dump -Fc --file "$backup" "$DATABASE_URL"');
    expect(remote).toContain('sha256sum "$backup"');
    expect(remote).toContain('migrate-db <customer> --source-rev FULL_REV --store-path STORE_PATH');
    expect(remote).toContain('apply-db-migrations.js" apply');
    expect(remote).toContain('migration runner did not emit completion JSON');
    expect(remote).toContain('cutover-status <customer>');
    expect(remote).toContain('merge-base --is-ancestor "$rev" "$origin"');
    expect(remote).toContain('repository HEAD is not aligned to approved revision');
    expect(remote).toContain('scp -q "$script_dir/../nix-app/cutover-production"');
    expect(remote).toContain('control-plane tooling may be newer than the approved app TARGET');
    expect(remote).toContain('promote-verify <customer>');
    expect(remote).toContain('cutover phase is $phase, not done');
    expect(remote).toContain('manage-customer-generations promote');
    expect(remote).toContain("assert r.get('current')==expected");
    expect(remote.indexOf("runtime_box_smoke.get('doctor')=='ok'")).toBeLessThan(remote.lastIndexOf('manage-customer-generations promote'));
    expect(remote).toContain("assert health.get('sourceRev')==rev");
    expect(remote).toContain('env -u PDF_EXPORT_RENDERER_MODE -u NIX_RENDERER_BIN "$store/bin/tower-app-pdf-smoke"');
    expect(remote).toContain('"$store/bin/tower-app-document-smoke"');
    expect(remote).toContain('live Tower process lacks exact RUNTIME_BOX_IMAGE');
    expect(remote).toContain('RUNTIME_BOX_IMAGE="$runtime_box_image" TOWER_RUNTIME_BOX_SMOKE_PROCESS_PID="$pm2_pid"');
    expect(remote).toContain("document_smoke=={'python':'nix-document-runtime','pdf_view':'ok','pdf_read':'ok','excel':'ok'}");
    expect(remote).toContain("runtime_box_smoke.get('dockerApi')=='ok'");
    expect(remote).toContain("runtime_box_smoke.get('containerStart')=='ok'");
    expect(remote).toContain("'runtimeBoxFunctional':runtime_box_smoke");
    expect(remote).not.toContain("assert env.get('PDF_EXPORT_RENDERER_MODE')=='nix'");
    expect(remote).not.toContain("assert env.get('NIX_RENDERER_BIN')==store+'/bin/tower-nix-render'");
    expect(remote).toContain("os.path.isfile(store+'/bin/tower-nix-render')");
    expect(remote).toContain("os.access(store+'/bin/tower-nix-render', os.X_OK)");
    expect(remote).toContain("pdf_smoke.get('fallback') is False");
    expect(remote).toContain('def last_json(raw):');
    expect(remote).toContain('map(last_json,sys.argv[5:8])');
    expect(remote).toContain("raise ValueError('command output did not contain valid JSON')");
    expect(remote).not.toContain('health,external,roots,pm2_json,pdf_smoke,document_smoke,runtime_box_smoke=map(json.loads,sys.argv[1:8])');
    expect(remote).toContain('hostRollbackArtifact');
    expect(remote).toContain('--project-root "$PWD"');
  });

  it('classifies cumulative customer changes and keeps every customer transfer behind explicit apply', () => {
    expect(fast).toContain('fleet-deploy-fast plan');
    expect(fast).toContain('fleet-deploy-fast prepare');
    expect(fast).toContain('fleet-deploy-fast apply --approve-rev FULL_REV');
    expect(fast).not.toContain('Operator production must already run exact revision');
    expect(fast).toContain("'operatorRunningRev':plan.get('operatorCurrentRev')");
    expect(fast).toContain("'operatorMatchesTarget':plan.get('operatorCurrentRev')==rev");
    expect(fast).toContain('Operator production');
    expect(fast).toContain('and the Fleet target may run different origin/main revisions');
    expect(fast).toContain("'db-migration'");
    expect(fast).toContain("'runtime-box'");
    expect(fast).toContain("'nix-runtime'");
    expect(fast).toContain("'dbMigrationRequired':bool(plan.get('dbMigrationRequired'))");
    expect(fast).toContain("'customerMigrationStatus':plan.get('customerMigrationStatus',[])");
    expect(fast).toContain("'auth-or-acl'");
    expect(fast).toContain("'file-storage'");
    expect(fast).toContain("'ingress'");
    expect(fast).toContain("'skipCanary':risk=='low'");
    expect(fast).toContain("current=row.get('sourceRev')");
    expect(fast).toContain("print(f'{current}..{target}')");
    expect(fast).toContain("['git','-C',repo,'diff','--name-only',span]");
    expect(fast).toContain("'customerTransferStarted':False");
    expect(fast).toContain("x['customerMutation']=False");
    expect(fast).toContain('args+=(--skip-canary)');
  });

  it('uses a receipt-backed runtime fast path and keeps full recursive verification available for audits', () => {
    expect(prefetch).toContain('--verification copy-enforced');
    expect(prefetch).toContain('runtime-box-verified-${archive_sha}.json');
    expect(prefetch).toContain('runtime_verification="receipt"');
    expect(prefetch).toContain('sha256sum "$archive"');
    expect(prefetch).toContain('docker image inspect "$base_id" "$operator_id"');
    expect(prefetch).toContain('ControlMaster=auto');
    expect(prefetch).toContain('ControlPersist=120');
    expect(prefetch).toContain('helper_transfer="reused"');
    expect(prefetch).toContain('local_prefetch_sha=');
    expect(prefetch).toContain('"status":"wrapper-complete"');
    expect(signedClosure).toContain('--verification full|copy-enforced');
    expect(signedClosure).toContain('[[ "$verification" = full ]] && source_verify+=(--recursive)');
    expect(signedClosure).toContain('[[ "$verification" = full ]] && verify_args+=(--recursive)');
    expect(signedClosure).toContain('record_timing query');
    expect(signedClosure).toContain('record_timing sourceVerify');
    expect(signedClosure).toContain('record_timing copy');
    expect(signedClosure).toContain('record_timing destinationVerify');
    expect(signedClosure).toContain('"closurePathCount":%s');
    expect(signedClosure).toContain('"missingPathCount":%s');
    expect(signedClosure).toContain('--receipt PATH');
    expect(signedClosure).toContain('TOWER_PREFETCH_VERIFICATION_RECEIPT_MAX_AGE_SEC:-3600');
    expect(signedClosure).toContain("x.get('publicKeySha256')==sys.argv[4]");
    expect(signedClosure).toContain('time.time()-float(x.get(\'verifiedEpoch\',0))<=int(sys.argv[5])');
    expect(signedClosure).toContain('receipt_hit="true"');
    expect(signedClosure).toContain('&& "$receipt_hit" = false ]]; then');
    expect(signedClosure).toContain('"receiptHit":%s');
    expect(prefetch).toContain('verification-receipts/$(basename "$store_path").json');
  });

  it('wraps approved rollout in a durable async run with disk guard and resumable targets', () => {
    expect(durableRun).toContain('$HOME/.tower-fleet-runs');
    expect(durableRun).toContain('wait --run-id ID [--timeout-sec N]');
    expect(durableRun).toContain('wrapperCompletedAt');
    expect(durableRun).toContain("x['phase']='failed'; x['message']=detail");
    expect(durableRun).toContain("row['status']='failed'; row['phase']='preflight'");
    expect(durableRun).toContain('timed out waiting for terminal state');
    expect(durableRun).toContain('[[ "$phase" = done ]] || exit 1');
    expect(durableRun).toContain('disk-status');
    expect(durableRun).toContain('TOWER_FLEET_RUN_MIN_FREE_GIB:-8');
    expect(durableRun).toContain('TOWER_FLEET_RUN_MAX_USED_PERCENT:-94');
    expect(durableRun).toContain('resume approval revision mismatch');
    expect(durableRun).toContain('--approve-db-migrations');
    expect(durableRun).toContain('args+=(--approve-db-migrations "$migration")');
    expect(durableRun).toContain("r.get('status')=='verified'");
    expect(durableRun).toContain('"status":"started","mode":"async"');
    expect(durableRun).toContain("'phase':'queued'");
    expect(durableRun).toContain("'customerStates'");
    expect(durableRun).toContain("'summary'");
    expect(durableRun).toContain('sync_state()');
    expect(durableRun).toContain('compat_state.customers');
    expect(durableRun).toContain("'resumedFromRunId':resumed_from or None");
    expect(durableRun).toContain("'canaryEnabled':canary=='1'");
    expect(durableRun).toContain('args+=(--canary)');
    expect(durableRun).toContain("state['statePath']=state_path");
    expect(durableRun).toContain("state['logPath']=log_path");
    expect(durableRun).not.toContain('echo "log: $runs_root/$run_id/rollout.log"');
    expect(durableRun).not.toContain('follow_state \'$run_dir\' \'$compat_state\' "\\$@"" runner "$upgrade" "${args[@]}" </dev/null >>"$run_dir/rollout.log"');
    expect(remote).toContain('fleet-nix-remote disk-status <customer>');
    expect(remote).toContain("'freeBytes'");
  });

  it('derives customer public OAuth config from the fleet registry domain', () => {
    expect(remote).toContain('fleet-nix-remote config-invariant <customer>');
    expect(remote).toContain('expected_public_url="https://$domain"');
    expect(remote).toContain('expected_google_redirect_uri="$expected_public_url/api/auth/google/callback"');
    expect(remote).toContain("'publicConfigInvariant':config_checks");
    expect(remote).toContain("'envFileGoogleRedirectUri':env_file_redirect or None");
    expect(remote).toContain("'pm2GoogleRedirectUri':pm2_redirect");
    expect(remote).toContain("'healthPublicUrl':health_public");
    expect(remote).toContain("'PUBLIC_URL':sys.argv[4]");
    expect(remote).toContain("'GOOGLE_REDIRECT_URI':sys.argv[5]");
    expect(remote).toContain("assert health.get('publicUrl')==expected_public_url");
    expect(remote).toContain("assert env.get('PUBLIC_URL')==expected_public_url");
    expect(remote).toContain("assert env.get('GOOGLE_REDIRECT_URI')==expected_google_redirect_uri");
    expect(remote).toContain("'expectedGoogleRedirectUri':expected_google_redirect_uri");
  });

  it('offers a thin any-customer urgent patch entrypoint without weakening approval boundaries', () => {
    expect(fleetPatch).toContain('fleet-patch prepare CUSTOMER');
    expect(fleetPatch).toContain('fleet-patch apply CUSTOMER --approve-rev FULL_REV');
    expect(fleetPatch).toContain('fleet-patch follow-up CUSTOMER');
    expect(fleetPatch).toContain('changes only the named customer');
    expect(fleetPatch).toContain('run follow-up only after separate approval');
    expect(fleetPatch).toContain('"$prepare_cmd" plan --source-rev "$rev" --targets "$customer" >/dev/null');
    expect(fleetPatch).toContain('"$run_cmd" "${args[@]}"');
    expect(fleetPatch).toContain('"$followup_cmd" "$customer"');
    expect(fleetPatch).not.toContain('prod-upgrade-fast');
  });

  it('exposes plan, apply and status entrypoints from start.sh', () => {
    expect(start).toContain('fleet-upgrade-plan)');
    expect(start).toContain('upgrade-fleet-production plan "$@"');
    expect(start).toContain('fleet-upgrade)');
    expect(start).toContain('upgrade-fleet-production apply "$@"');
    expect(start).toContain('fleet-upgrade-status)');
    expect(start).toContain('--approve-db-migrations <full-rev>');
    expect(start).toContain('fleet-deploy-fast)');
    expect(start).toContain('fleet-deploy-fast plan|prepare');
    expect(start).toContain('fleet-deploy-run)');
    expect(start).toContain('bash scripts/fleet/fleet-deploy-run "$@"');
    expect(start).toContain('fleet-deploy-run apply --approve-rev');
    expect(start).toContain('fleet-deploy-run status --run-id');
    expect(start).toContain('fleet-deploy-run resume --run-id');
    expect(start).toContain('fleet-patch)');
    expect(start).toContain('bash scripts/fleet/fleet-patch "$@"');
    expect(start).toContain('fleet-patch prepare <customer>');
    expect(start).toContain('fleet-patch apply <customer> --approve-rev');
    expect(start).toContain('fleet-patch follow-up <customer>');
    expect(start).toContain('run only after separate approval');
  });
});
