#!/usr/bin/env bash
# ──────────────────────────────────────────────────────────
# setup-le-wildcard.sh — Tower wildcard SSL 표준 셋업 (Let's Encrypt + Cloudflare DNS-01)
# version: 2026-04-26
#
# 무엇을 하나:
#   1. certbot + cloudflare-dns plugin 설치
#   2. Cloudflare API token 으로 DNS-01 wildcard cert 발급 (*.<DOMAIN> + <DOMAIN>)
#   3. nginx wildcard server block 추가 (/sites/ 와 같은 root 서빙)
#   4. certbot.timer 자동 갱신 + nginx reload hook
#
# 전제 조건:
#   - Cloudflare DNS 에 *.<DOMAIN> A 레코드가 origin IP 로 ⚪ DNS-only (gray cloud) 로 등록돼있을 것
#   - Azure NSG 또는 firewall 에 443 포트 허용
#   - root/sudo 권한
#   - .env 또는 환경변수에 CLOUDFLARE_API_TOKEN (Zone:DNS:Edit 권한)
#   - 기존 nginx 가 80 listen 하는 server block 이 있어야 함 (이 스크립트는 wildcard 만 추가)
#
# 사용:
#   sudo bash setup-le-wildcard.sh tower.tower.example.com /home/USER/workspace/published/sites
#   sudo bash setup-le-wildcard.sh demo-org.tower.example.com /home/USER/workspace/published/sites EMAIL
#
# 결정 노트: workspace/decisions/2026-04-26-publishing-storage-restructure.md (Phase 7)
# ──────────────────────────────────────────────────────────
set -euo pipefail

DOMAIN="${1:-}"
SITES_ROOT="${2:-}"
EMAIL="${3:-${LE_EMAIL:-admin@tower.example.com}}"

if [[ -z "$DOMAIN" || -z "$SITES_ROOT" ]]; then
  echo "사용법: sudo bash $0 <DOMAIN> <SITES_ROOT> [EMAIL]"
  echo "  예:  sudo bash $0 tower.tower.example.com /home/tower/workspace/published/sites"
  exit 1
fi

if [[ $EUID -ne 0 ]]; then
  echo "❌ root 권한 필요. sudo 로 실행하세요."
  exit 1
fi

# ── CF token 찾기 ──
CF_TOKEN="${CLOUDFLARE_API_TOKEN:-}"
if [[ -z "$CF_TOKEN" && -f "$HOME/tower/.env" ]]; then
  CF_TOKEN=$(grep '^CLOUDFLARE_API_TOKEN=' "$HOME/tower/.env" | cut -d= -f2-)
fi
if [[ -z "$CF_TOKEN" && -f "/home/$(logname 2>/dev/null || echo $SUDO_USER)/tower/.env" ]]; then
  CF_TOKEN=$(grep '^CLOUDFLARE_API_TOKEN=' "/home/$(logname 2>/dev/null || echo $SUDO_USER)/tower/.env" | cut -d= -f2-)
fi
if [[ -z "$CF_TOKEN" ]]; then
  echo "❌ CLOUDFLARE_API_TOKEN 을 환경변수 또는 ~/tower/.env 에서 찾을 수 없음"
  exit 1
fi

echo "🚀 Wildcard SSL 셋업 시작"
echo "   도메인: $DOMAIN"
echo "   사이트 root: $SITES_ROOT"
echo "   이메일: $EMAIL"
echo ""

# ── 1. certbot + plugin 설치 ──
echo "📦 [1/5] certbot + cloudflare DNS plugin 설치 (이미 있으면 skip)..."
if ! dpkg -l | grep -q "python3-certbot-dns-cloudflare"; then
  apt-get update -qq
  apt-get install -y certbot python3-certbot-dns-cloudflare
fi

# ── 2. CF credentials 파일 ──
echo "🔑 [2/5] Cloudflare credentials 파일 작성..."
mkdir -p /etc/letsencrypt
cat > /etc/letsencrypt/cloudflare.ini <<EOF
dns_cloudflare_api_token = $CF_TOKEN
EOF
chmod 600 /etc/letsencrypt/cloudflare.ini

# ── 3. cert 발급 ──
echo "🛡  [3/5] LE wildcard cert 발급 ($DOMAIN + *.$DOMAIN)..."
# --expand 는 기존 단일-호스트 cert (apex 만 커버) 가 있을 때 와일드카드까지
# 포함해 자동 확장. 신규 발급 시는 무영향. demo-server (2026-04-28) 에서
# expand 프롬프트에 막힌 케이스 학습:
# workspace/decisions/2026-04-28-demo-server-wildcard-publishing.md
certbot certonly \
  --dns-cloudflare \
  --dns-cloudflare-credentials /etc/letsencrypt/cloudflare.ini \
  --dns-cloudflare-propagation-seconds 30 \
  -d "$DOMAIN" \
  -d "*.$DOMAIN" \
  --expand \
  --email "$EMAIL" \
  --agree-tos \
  --no-eff-email \
  --non-interactive

CERT_PATH="/etc/letsencrypt/live/$DOMAIN/fullchain.pem"
KEY_PATH="/etc/letsencrypt/live/$DOMAIN/privkey.pem"

if [[ ! -f "$CERT_PATH" ]]; then
  echo "❌ cert 발급 실패. 위 로그 확인."
  exit 1
fi
echo "   ✅ cert: $CERT_PATH"

# ── 3b. 홈 디렉토리 nginx (www-data) traverse 권한 보장 ──
# nginx 가 SITES_ROOT 까지 cd 하려면 경로 위 디렉토리 모두에 'others execute'
# 비트가 필요. ubuntu 기본 홈 권한 (drwxr-x---) 은 이게 빠져 있어서 wildcard
# server block 이 200 대신 404 를 반환하는 함정. demo-org 은 처음부터
# drwx--x--x 라 이슈 없었음.
SITES_PARENT="$(dirname "$SITES_ROOT")"
while [[ "$SITES_PARENT" != "/" ]]; do
  if [[ -d "$SITES_PARENT" ]]; then
    PERMS=$(stat -c '%a' "$SITES_PARENT")
    # 마지막 자리(others) 의 1 비트(execute) 가 0 이면 추가
    if (( (PERMS & 1) == 0 )); then
      echo "   🔧 chmod o+x $SITES_PARENT (was $PERMS — nginx traversal needed)"
      chmod o+x "$SITES_PARENT"
    fi
  fi
  SITES_PARENT="$(dirname "$SITES_PARENT")"
done

# ── 4. nginx wildcard server block ──
echo "🌐 [4/5] nginx wildcard server block 추가..."
NGINX_FILE="/etc/nginx/sites-available/wildcard-${DOMAIN}"
if [[ -f "$NGINX_FILE" ]]; then
  cp "$NGINX_FILE" "${NGINX_FILE}.bak.$(date +%s)"
  echo "   기존 파일 백업"
fi

cat > "$NGINX_FILE" <<NGINX_EOF
# wildcard-${DOMAIN} — auto-generated by setup-le-wildcard.sh
# Serves <slug>.${DOMAIN} from ${SITES_ROOT}/<slug>/

server {
    listen 80;
    server_name ~^(?<slug>[^.]+)\.${DOMAIN//./\\.}\$;
    return 301 https://\$host\$request_uri;
}

server {
    listen 443 ssl;
    listen [::]:443 ssl;
    server_name ~^(?<slug>[^.]+)\.${DOMAIN//./\\.}\$;

    ssl_certificate     ${CERT_PATH};
    ssl_certificate_key ${KEY_PATH};
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_prefer_server_ciphers off;

    root ${SITES_ROOT}/\$slug;
    index index.html;
    autoindex off;

    add_header X-Robots-Tag "noindex, nofollow, noarchive" always;

    types {
        text/html html htm;
        text/css css;
        application/javascript js mjs;
        application/json json;
        image/png png;
        image/jpeg jpg jpeg;
        image/gif gif;
        image/svg+xml svg;
        image/x-icon ico;
        application/pdf pdf;
        font/woff2 woff2;
        font/woff woff;
        application/octet-stream ttf otf;
        text/plain txt;
    }

    location ~ /\\. {
        deny all;
        return 404;
    }

    location / {
        try_files \$uri \$uri/ \$uri/index.html =404;
    }

    access_log /var/log/nginx/wildcard-${DOMAIN}.access.log;
    error_log  /var/log/nginx/wildcard-${DOMAIN}.error.log;
}
NGINX_EOF

ln -sf "$NGINX_FILE" "/etc/nginx/sites-enabled/wildcard-${DOMAIN}"

if ! nginx -t; then
  echo "❌ nginx 설정 에러. 롤백."
  rm -f "/etc/nginx/sites-enabled/wildcard-${DOMAIN}"
  exit 1
fi

systemctl reload nginx
echo "   ✅ nginx reloaded"

# ── 5. 자동 갱신 hook ──
echo "🔄 [5/5] 자동 갱신 + nginx reload hook 설정..."
mkdir -p /etc/letsencrypt/renewal-hooks/deploy
cat > /etc/letsencrypt/renewal-hooks/deploy/nginx-reload.sh <<'EOF'
#!/bin/sh
systemctl reload nginx
EOF
chmod +x /etc/letsencrypt/renewal-hooks/deploy/nginx-reload.sh

systemctl enable --now certbot.timer 2>/dev/null || true

echo ""
echo "✅ 셋업 완료!"
echo ""
echo "검증 명령어:"
echo "  curl -sk -o /dev/null -w 'HTTP %{http_code}\\n' \"https://test-xyz.${DOMAIN}/\""
echo "  curl -sk -o /dev/null -w 'HTTP %{http_code}\\n' \"https://${DOMAIN}/sites/<some-slug>/\""
echo ""
echo "다음 갱신 예정:"
systemctl list-timers certbot.timer --no-pager 2>/dev/null | head -3 || true
